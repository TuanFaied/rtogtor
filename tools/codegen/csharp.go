package main

import (
	"fmt"
	"sort"
	"strings"
)

// csharpOutput maps schema files to the generated C# file holding their
// classes.
var csharpFiles = map[string]string{
	"mapping.schema.json":         "Mapping.g.cs",
	"schema-metadata.schema.json": "SchemaMetadata.g.cs",
	"plan.schema.json":            "Plan.g.cs",
	"report.schema.json":          "Report.g.cs",
	"run-state.schema.json":       "RunState.g.cs",
	"protocol.schema.json":        "Protocol.g.cs",
}

const csharpNamespace = "RtoGtoR.Model"

func csharpHeader(source string) string {
	return "// <auto-generated>\n" +
		"//   Generated by tools/codegen from " + source + ". DO NOT EDIT.\n" +
		"//   Regenerate with: go -C tools/codegen run . -repo ../.. (from the repository root).\n" +
		"// </auto-generated>\n" +
		"#nullable enable\n\n"
}

// csharpKeywords are reserved in C#; property names never collide with them
// because they are PascalCase, but the list guards future additions.
var csharpKeywords = map[string]bool{"Object": false}

func (m *Model) csType(t TypeRef) string {
	var s string
	switch t.Kind {
	case KString:
		s = "string"
	case KInt:
		s = "long"
	case KFloat:
		s = "double"
	case KBool:
		s = "bool"
	case KJSON:
		// JsonElement can hold null itself.
		return "global::System.Text.Json.JsonElement"
	case KObject:
		s = m.names[t.Class]
	case KList:
		s = "global::System.Collections.Generic.IReadOnlyList<" + m.csType(*t.Elem) + ">"
	}
	if t.Nullable {
		s += "?"
	}
	return s
}

func xmlEscape(s string) string {
	r := strings.NewReplacer("&", "&amp;", "<", "&lt;", ">", "&gt;")
	return r.Replace(s)
}

func writeDoc(b *strings.Builder, indent, doc string) {
	if doc == "" {
		return
	}
	b.WriteString(indent + "/// <summary>\n")
	for _, line := range wrap(xmlEscape(doc), 90) {
		b.WriteString(indent + "/// " + line + "\n")
	}
	b.WriteString(indent + "/// </summary>\n")
}

func wrap(s string, width int) []string {
	words := strings.Fields(s)
	var lines []string
	cur := ""
	for _, w := range words {
		if cur != "" && len(cur)+1+len(w) > width {
			lines = append(lines, cur)
			cur = w
			continue
		}
		if cur == "" {
			cur = w
		} else {
			cur += " " + w
		}
	}
	if cur != "" {
		lines = append(lines, cur)
	}
	return lines
}

// emitCSharp returns file name -> contents.
func (m *Model) emitCSharp(codes []ErrorCode) (map[string]string, error) {
	byFile := map[string][]*Class{}
	for _, key := range m.order {
		c := m.classes[key]
		byFile[c.File] = append(byFile[c.File], c)
	}
	out := map[string]string{}
	for file, classes := range byFile {
		name, ok := csharpFiles[file]
		if !ok {
			return nil, fmt.Errorf("no C# output file for %s", file)
		}
		sort.SliceStable(classes, func(i, j int) bool { return classes[i].Name < classes[j].Name })
		var b strings.Builder
		b.WriteString(csharpHeader("specs/" + file))
		b.WriteString("using System.Text.Json.Serialization;\n\n")
		b.WriteString("namespace " + csharpNamespace + ";\n")
		for _, c := range classes {
			b.WriteString("\n")
			writeDoc(&b, "", c.Doc)
			b.WriteString("public sealed record class " + c.Name + "\n{\n")
			for i, f := range c.Fields {
				if i > 0 {
					b.WriteString("\n")
				}
				writeDoc(&b, "    ", f.Doc)
				prop := f.Name
				if prop == c.Name || csharpKeywords[prop] {
					prop += "Value"
				}
				fmt.Fprintf(&b, "    [JsonPropertyName(%q)]\n", f.JSONName)
				typ := m.csType(f.Type)
				if f.Required {
					// Required members must be present when deserializing;
					// nullable ones are written even when null.
					fmt.Fprintf(&b, "    public required %s %s { get; init; }\n", typ, prop)
				} else {
					if !strings.HasSuffix(typ, "?") && f.Type.Kind != KJSON {
						typ += "?"
					}
					if f.Type.Kind == KJSON {
						typ = "global::System.Text.Json.JsonElement?"
					}
					b.WriteString("    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]\n")
					fmt.Fprintf(&b, "    public %s %s { get; init; }\n", typ, prop)
				}
			}
			b.WriteString("}\n")
		}
		out[name] = b.String()
	}
	out["ErrorCodes.g.cs"] = emitCSharpErrorCodes(codes)
	return out, nil
}

// errorConstName turns "RTG-MAP-005" into "Map005".
func errorConstName(code string) string {
	parts := strings.Split(code, "-")
	return pascal(strings.ToLower(parts[1])) + parts[2]
}

func emitCSharpErrorCodes(codes []ErrorCode) string {
	var b strings.Builder
	b.WriteString(csharpHeader("specs/error-codes.json"))
	b.WriteString("using System.Collections.Generic;\n\n")
	b.WriteString("namespace RtoGtoR;\n\n")
	b.WriteString("/// <summary>Stable RtoGtoR error codes (specs/error-codes.json).</summary>\n")
	b.WriteString("public static class ErrorCodes\n{\n")
	for _, c := range codes {
		writeDoc(&b, "    ", c.Title+". "+c.Meaning)
		if c.Deprecated {
			b.WriteString("    [System.Obsolete(\"This error code is deprecated.\")]\n")
		}
		fmt.Fprintf(&b, "    public const string %s = %q;\n\n", errorConstName(c.Code), c.Code)
	}
	b.WriteString("    /// <summary>Every defined code with its severity, retryability and remediation.</summary>\n")
	b.WriteString("    public static IReadOnlyDictionary<string, ErrorCodeInfo> All { get; } = new Dictionary<string, ErrorCodeInfo>\n    {\n")
	for _, c := range codes {
		fmt.Fprintf(&b, "        [%q] = new(%q, %q, ErrorSeverity.%s, %t, %q, %q),\n",
			c.Code, c.Code, c.Title, pascal(c.Severity), c.Retryable, c.Meaning, c.Remediation)
	}
	b.WriteString("    };\n}\n")
	return b.String()
}
